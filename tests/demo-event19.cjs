'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path');
require('../web/demo-event.js');
require('../web/alarm-event.js');
require('../web/replay-timeline.js');
const demo=globalThis.WaveAssureDemoEvent;
assert.equal(demo.sampleTime(20),5);
assert.equal(demo.sampleTime(6),3);
assert.equal(demo.sampleTime(360),5);
assert.equal(demo.sampleTime(0),null);
assert.equal(demo.sampleTime(NaN),null);
assert.equal(demo.sampleTime(-3),null);
const reason=demo.explanation(5);
assert.match(reason.status,/DEMO event/);
assert.match(reason.reason,/optional beep is generated by the browser/);
assert.match(reason.reason,/NOT an original patient-monitor buzzer/);
assert.match(reason.source,/Temporary browser-only/);
assert.match(reason.classification,/No genuine or false medical alarm label/);
const unknown=globalThis.WaveAssureAlarmEvent.explain({
 metadata:{origin:'local_csv_unverified',parent_id:null},
 alarm_time_s:null,reference_label:'Unlabeled',alarm_time_source:null,source_reference:''},null);
assert.match(unknown.status,/No recorded alarm timestamp/);
const real=globalThis.WaveAssureAlarmEvent.explain({
 metadata:{origin:'wfdb_research',parent_id:null},
 alarm_time_s:300,reference_label:'False',alarm_time_source:'dataset_annotation',source_reference:'VTaC'},300);
assert.match(real.status,/false VT alarm/i);
assert.match(real.reason,/does NOT establish a normal heart rhythm/);
assert.equal(globalThis.WaveAssureReplay.crossedEvent(4.9,5.0,5),true);
assert.equal(globalThis.WaveAssureReplay.crossedEvent(5,5.1,5),false);
const app=fs.readFileSync(path.join(__dirname,'../web/app.js'),'utf8');
const html=fs.readFileSync(path.join(__dirname,'../web/index.html'),'utf8');
for(const marker of ['hasDemoMarker()', 'toggleDemoMarker()', 'demoMarker=null',
 'Window.WaveAssureDemoEvent']) {
 if(marker.startsWith('Window.'))continue;
 assert.ok(app.includes(marker),marker);
}
assert.ok(app.includes('window.WaveAssureDemoEvent.sampleTime'));
assert.ok(app.includes('window.WaveAssureDemoEvent.explanation'));
assert.ok(app.includes('current=loaded;demoMarker=null'),'new recording clears temporary marker');
assert.ok(app.includes("hasDemoMarker()?'DEMO ':'EVENT '"),'marker is labeled DEMO on canvas');
assert.ok(html.includes('id="demoMarkerToggle"'));
assert.ok(html.indexOf('/static/demo-event.js')<html.indexOf('/static/app.js'));
assert.equal((html.match(/type="file"/g)||[]).length,1,'single dataset file input preserved');
console.log('Demo marker: timestamp, false/unknown provenance, safe beep, reset, hover and UI contracts PASS');
