/* UI-only event marker. Not a measured alarm, not persisted, not diagnostic. */
(function(root){
 'use strict';
 function sampleTime(duration){
   const d=Number(duration);
   if(!Number.isFinite(d)||d<=0)return null;
   // A visible, easy-to-test timestamp in a short or long research recording.
   return Math.min(5,d/2);
 }
 function explanation(time){
   return {
     status:'DEMO event — no actual alarm detected',
     classification:'Artificial marker created by the user. No genuine or false medical alarm label.',
     reason:'You selected Show test event. The optional beep is generated by the browser when the moving playback cursor reaches this marker. It is NOT an original patient-monitor buzzer, a measured threshold breach, or evidence of a normal or abnormal condition.',
     source:'Temporary browser-only demonstration marker at '+Number(time).toFixed(3)+' seconds. Not read from the uploaded dataset, not saved to the clinical evidence record.',
     disclaimer:'No original alarm audio, patient condition, diagnosis, or recorded alarm cause was determined.'
   };
 }
 root.WaveAssureDemoEvent=Object.freeze({sampleTime,explanation});
})(typeof window==='undefined'?globalThis:window);
